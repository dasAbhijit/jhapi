// Builds cloud/Code.gs: the app's parsers and sheet layout (src/cloud/entry.ts) bundled as the global
// `JhapiCore`, followed by the hand-written script in cloud/main.js. Paste Code.gs into the sheet's
// Apps Script editor. CI rebuilds it and fails if the committed copy is out of date.
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = await build({
  entryPoints: [join(root, 'src/cloud/entry.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'JhapiCore',
  target: 'es2019',
  platform: 'neutral',
  charset: 'utf8',
  legalComments: 'none',
  write: false,
})
const bundle = out.outputFiles[0].text
const main = readFileSync(join(root, 'cloud/main.js'), 'utf8')
const header = `// Jhapi Apps Script. GENERATED by scripts/build-cloud.mjs from src/cloud/entry.ts and cloud/main.js.
// Do not edit by hand: change the sources and run \`npm run build:cloud\`.
// Copy this whole file into Extensions > Apps Script > Code.gs of Jhapi's own Google Sheet.

`
writeFileSync(join(root, 'cloud/Code.gs'), header + bundle + '\n' + main)
console.log(`cloud/Code.gs written (${Math.round((header.length + bundle.length + main.length) / 1024)} KB)`)
